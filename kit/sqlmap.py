#!/usr/bin/env python3
"""Step 2 — endpoint to table, from the SQL log joined with the access log by trace id.

Also finds the tables nobody touches: declared in the schema, absent from every statement.
"""
from __future__ import annotations

import re
from collections import defaultdict

from common import ROOT, SAMPLES, access, endpoint_of, sql

TABLE = re.compile(r"\b(?:from|join|into|update)\s+([a-z_][a-z0-9_]*)", re.I)
SCHEMA_TABLE = re.compile(r"create\s+(?:temp\s+)?table\s+(?:if\s+not\s+exists\s+)?([a-z_][a-z0-9_]*)", re.I)


def schema_tables() -> set[str]:
    """Any table the schema or the seed data declares, wherever it lives."""
    tables = set()
    sources = list(SAMPLES.glob("*.sql")) + list((ROOT / "legacy-app/src/main/resources").glob("*.sql"))
    for f in sources:
        tables |= {t.lower() for t in SCHEMA_TABLE.findall(f.read_text(encoding="utf-8"))}
    return tables


def main() -> None:
    trace_endpoint = {}
    for r in access():
        trace_endpoint.setdefault(r.get("trace"), f"{r['method']} {endpoint_of(r['path'])}")

    by_endpoint: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    touched: set[str] = set()
    for row in sql():
        ep = trace_endpoint.get(row.get("trace"), "(no trace in access log)")
        for t in TABLE.findall(row.get("sql", "")):
            name = t.lower()
            if name in ("select", "values", "set"):
                continue
            touched.add(name)
            by_endpoint[ep][name] += 1

    declared = schema_tables()
    orphans = sorted(declared - touched)

    doc = ["# Endpoint to table", "",
           "Generated by `kit/sqlmap.py`: the SQL log carries a trace id, the access log carries the same id,",
           "so every statement is attributed to the endpoint that caused it.", "",
           "| Endpoint | Tables | Statements |", "|---|---|---|"]
    for ep, tables in sorted(by_endpoint.items(), key=lambda kv: -sum(kv[1].values())):
        doc.append(f"| `{ep}` | {', '.join(sorted(tables))} | {sum(tables.values())} |")
    doc += ["", "## Tables no statement touches", ""]
    doc += [f"- `{o}` — declared in the schema, absent from every logged statement (orphan or dead)" for o in orphans] \
        or ["- none"]

    doc += ["", "## Queries to fix first", "",
            "Grouped by endpoint, highest statement count first — that is where an N+1 hides:", ""]
    for ep, tables in sorted(by_endpoint.items(), key=lambda kv: -sum(kv[1].values()))[:3]:
        doc.append(f"- `{ep}` — {sum(tables.values())} statements for one request")

    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/ENDPOINT-DB.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    print(f"endpoints_with_sql={len(by_endpoint)} tables_touched={len(touched)} orphans={len(orphans)}")
    print("wrote docs/ENDPOINT-DB.md")


if __name__ == "__main__":
    main()
