#!/usr/bin/env python3
"""Step 1 — inventory: what exists, what is used, what is dead.

Sources: access log (real traffic) + controller annotations (declared endpoints).
Output: docs/INVENTORY.md and a ranked work list, because 200 services cannot be done alphabetically.
"""
from __future__ import annotations

import re
from collections import Counter

from common import APP, ROOT, access, endpoint_of, java_files

MAPPING = re.compile(r'@(Get|Post|Put|Delete|Patch)Mapping\(\s*(?:value\s*=\s*)?"([^"]+)"')


def declared_endpoints() -> dict[str, str]:
    """method+path -> java file, parsed from the controller annotations."""
    out: dict[str, str] = {}
    for f in java_files():
        for verb, path in MAPPING.findall(f.read_text(encoding="utf-8")):
            out[f"{verb.upper()} {path}"] = str(f.relative_to(ROOT))
    return out


def traffic() -> Counter:
    hits: Counter = Counter()
    for r in access():
        hits[f"{r['method']} {endpoint_of(r['path'])}"] += 1
    return hits


def dead_classes() -> list[str]:
    """A class whose simple name never appears in ANY other file of the source tree."""
    texts = {str(f): f.read_text(encoding="utf-8") for f in java_files()}
    names = {f.stem: str(f) for f in java_files()}
    external = Counter()
    for name, own in names.items():
        for path, text in texts.items():
            if path != own and name in text:
                external[name] += 1
    # Spring discovers these by scanning, so "referenced by nothing" is a false positive for them.
    stereotype = re.compile(r"@(RestController|Controller|Service|Repository|Component|Configuration)\b")
    entry_points = {"LegacyApplication"} | {n for n, p in names.items()
                                            if stereotype.search(texts[p])}
    return sorted(n for n in names if external[n] == 0 and n not in entry_points)


def has_test(endpoint: str) -> bool:
    tests = list((APP / "src/test").rglob("*.java")) if (APP / "src/test").exists() else []
    needle = endpoint.split(" ", 1)[1].replace("{id}", "")
    for t in tests:
        if needle.strip("/").split("/")[-1] in t.read_text(encoding="utf-8"):
            return True
    return False


def main() -> None:
    declared = declared_endpoints()
    hits = traffic()
    total = sum(hits.values()) or 1

    rows = []
    for key in sorted(set(declared) | set(hits)):
        h = hits.get(key, 0)
        rows.append((key, declared.get(key, "not in code"), h, 100.0 * h / total))
    rows.sort(key=lambda r: -r[2])

    dead = dead_classes()
    doc = [
        "# Inventory — what exists, what is used, what is dead",
        "",
        "Generated by `kit/inventory.py` from `samples/access.log` (traffic) and the controller annotations.",
        f"Traffic sample: **{total} requests** across **{len(hits)} distinct endpoints**.",
        "",
        "| Endpoint | Declared in | Hits | % traffic |",
        "|---|---|---|---|",
    ]
    doc += [f"| `{k}` | {src} | {h} | {p:.1f}% |" for k, src, h, p in rows]
    doc += ["", "## Ranked work list", "",
            "Order is `traffic% x has-no-test x criticality`, never alphabetical:", ""]
    for k, src, h, p in rows:
        if h == 0:
            continue
        doc.append(f"{rows.index((k, src, h, p)) + 1}. `{k}` — {p:.1f}% of traffic, "
                   f"source {src}, test {'yes' if has_test(k) else 'NONE'}")
    doc += ["", "## Dead code", "",
            "Class names that appear nowhere else in the source tree. They cost coverage and confuse readers;",
            "the revival removes them (git history keeps them):", ""]
    doc += [f"- `{d}`" for d in dead] or ["- none detected"]

    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/INVENTORY.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    print(f"endpoints={len(rows)} traffic={total} dead={len(dead)}")
    print(f"top: {rows[0][0]} ({rows[0][3]:.1f}%)")
    print("wrote docs/INVENTORY.md")


if __name__ == "__main__":
    main()
