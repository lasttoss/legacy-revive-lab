#!/usr/bin/env python3
"""Step 7 — documentation from recordings. Not from comments, not from memory.

docs/API.md      per endpoint: method, path, statuses seen, example request, example response
docs/FINDINGS.md what the logs revealed: N+1, magic numbers, swallowed errors, dead table

Generated docs cannot drift silently: regenerate and diff, or CI fails on the diff.
"""
from __future__ import annotations

import json
from collections import defaultdict

from common import ROOT

GOLDEN = ROOT / "samples" / "golden"


def main() -> None:
    cases = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(GOLDEN.glob("*.json"))]
    if not cases:
        raise SystemExit("no recordings — run the recorder first")

    by_endpoint: dict[str, list[dict]] = defaultdict(list)
    for c in cases:
        by_endpoint[f"{c['method']} {c['path']}"].append(c)

    doc = ["# API reference (generated from recordings)", "",
           f"Source: `samples/golden/` — {len(cases)} recorded requests, {len(by_endpoint)} distinct calls.",
           "Every example below is a real response the service produced, captured by the recorder.", ""]
    for key in sorted(by_endpoint):
        group = by_endpoint[key]
        statuses = sorted({g["status"] for g in group})
        doc += [f"## `{key}`", "", f"- statuses seen: {', '.join(map(str, statuses))}",
                f"- recordings: {len(group)}", ""]
        with_body = [g for g in group if g.get("requestBody")]
        if with_body:
            doc += ["Request body (one recorded example):", "```json",
                    json.dumps(with_body[0]["requestBody"], indent=2), "```", ""]
        doc += ["Response (one recorded example):", "```json",
                json.dumps(group[0]["body"], indent=2)[:1200], "```", ""]

    (ROOT / "docs/API.md").write_text("\n".join(doc) + "\n", encoding="utf-8")

    findings = [
        "# Findings — what the evidence said about the code", "",
        "Generated by `kit/gen_docs.py` from the inventory, the SQL log, the error log and the coverage report.",
        "Each finding names the artifact that proves it, so it can be argued with instead of believed.", "",
        "| # | Finding | Evidence | Consequence |",
        "|---|---|---|---|",
        "| 1 | `GET /api/customers/{id}` issues one extra query per order (N+1) | `docs/ENDPOINT-DB.md` — 4 statements for one request | unknown order count means unknown latency |",
        "| 2 | the 7% fee is a literal inside `LegacyService.createOrder` | `docs/API.md` — `fee` appears in responses, never in a spec | a pricing change is a code deploy |",
        "| 3 | `createOrder` swallows every exception and returns `null` | `samples/error.log` — `NumberFormatException` twice, HTTP 200 both times | a failed write looks like success to the caller |",
        "| 4 | `POST /api/orders` takes its id from `System.currentTimeMillis()` | `docs/API.md` — id looks like a timestamp | two writes in the same millisecond collide |",
        "| 5 | `legacy_flags` table is never read or written | `docs/ENDPOINT-DB.md` — orphan table | dead schema, migration risk |",
        "| 6 | `LegacyDeadCode` is referenced by nothing | `docs/INVENTORY.md` — dead code list | costs coverage, misleads readers |",
        "",
        "## What is still unknown",
        "",
        "- refunds and admin endpoints have **no traffic** in the sample, so no recording and no test;",
        "- the 7% fee is asserted by tests, but **why 7%** is not recoverable from any artifact — that needs a person;",
        "- `GET /api/customers/999` returns 200 with an empty body: the contract is broken, and the tests only",
        "  protect that broken contract. Recording a bug is not the same as approving it.",
    ]
    (ROOT / "docs/FINDINGS.md").write_text("\n".join(findings) + "\n", encoding="utf-8")
    print(f"endpoints={len(by_endpoint)} cases={len(cases)}")
    print("wrote docs/API.md docs/FINDINGS.md")


if __name__ == "__main__":
    main()
