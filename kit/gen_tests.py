#!/usr/bin/env python3
"""Step 4 — generate the test suite from the recording.

One JUnit test per recorded case: "the answer has not changed". That is the only honest specification a
legacy service has. Volatile fields (the error timestamp) are masked before comparing.
"""
from __future__ import annotations

import json

from common import APP, ROOT

GOLDEN = ROOT / "samples" / "golden"
OUT = APP / "src/test/java/com/example/legacy/GoldenMasterTest.java"

HEADER = '''package com.example.legacy;

import com.fasterxml.jackson.databind.JsonNode;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.boot.web.server.LocalServerPort;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.http.*;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.*;

/**
 * GENERATED by kit/gen_tests.py from samples/golden/*.json — do not edit by hand.
 *
 * Each test replays one recorded request and asserts the status and the masked body are unchanged.
 * When a change is intentional: re-record, then review the diff in samples/golden. That review is the
 * specification change — there is no other documentation to update.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("test")     // test profile: tracing on, spans written to samples/spans.log
public class GoldenMasterTest {

    @LocalServerPort
    int port;

    @Autowired
    TestRestTemplate rest;

    private JsonNode golden(String id) throws Exception {
        Path p = GoldenSupport.dir().resolve(id + ".json");
        assertTrue(Files.exists(p), "missing recording " + p.toAbsolutePath());
        return GoldenSupport.M.readTree(new String(Files.readAllBytes(p), StandardCharsets.UTF_8));
    }

    private void replay(String id) throws Exception {
        JsonNode g = golden(id);
        String method = g.get("method").asText();
        String path = g.get("path").asText();
        JsonNode reqBody = g.get("requestBody");

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        HttpEntity<String> entity = new HttpEntity<>(
                reqBody == null || reqBody.isNull() ? null : reqBody.toString(), headers);

        ResponseEntity<String> resp = rest.exchange("http://localhost:" + port + path,
                HttpMethod.valueOf(method), entity, String.class);

        assertEquals(g.get("status").asInt(), resp.getStatusCodeValue(),
                "status changed for " + method + " " + path);
        // an empty body, a JSON null and a missing node all mean "no body": compare them as one
        com.fasterxml.jackson.databind.node.TextNode empty = com.fasterxml.jackson.databind.node.TextNode.valueOf("");
        JsonNode rawExpected = g.get("body");
        JsonNode rawActual = GoldenSupport.parse(resp.getBody());
        boolean expectedEmpty = rawExpected == null || rawExpected.isNull()
                || (rawExpected.isTextual() && rawExpected.asText().isEmpty());
        boolean actualEmpty = resp.getBody() == null || resp.getBody().isEmpty()
                || rawActual == null || rawActual.isNull() || rawActual.isMissingNode();
        JsonNode expected = expectedEmpty ? empty : GoldenSupport.mask(rawExpected);
        JsonNode actual = actualEmpty ? empty : GoldenSupport.mask(rawActual);
        assertEquals(expected, actual, "response body changed for " + method + " " + path);
    }
'''

FOOTER = "}\n"


def main() -> None:
    cases = sorted(GOLDEN.glob("*.json")) if GOLDEN.exists() else []
    if not cases:
        raise SystemExit("no golden recordings — run the recorder first")

    methods = []
    for p in cases:
        g = json.loads(p.read_text(encoding="utf-8"))
        methods.append(f'\n    /** {g["method"]} {g["path"]} -> {g["status"]} */\n'
                       f'    @Test\n    public void golden_{g["id"]}() throws Exception {{\n'
                       f'        replay("{g["id"]}");\n    }}\n')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "".join(methods) + FOOTER, encoding="utf-8")
    print(f"generated {len(cases)} tests -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
