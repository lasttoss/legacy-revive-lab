#!/usr/bin/env python3
"""Step 3 — error catalogue: group the error log by fingerprint, not by event.

Same idea as the OOM lab: strip numbers, ids and line numbers, then count distinct signatures.
"""
from __future__ import annotations

import hashlib
import re
from collections import defaultdict

from common import ROOT, SAMPLES, access, endpoint_of

BLOCK = re.compile(r"^(?P<ts>[\d\-T:.]+Z)\s+(?P<level>ERROR|WARN)\s+\[(?P<app>[^,\]]+),(?P<trace>[^\]]*)\]\s+(?P<logger>\S+)\s+-\s+(?P<msg>.*)$")
EXCEPTION = re.compile(r"^(?P<type>[a-zA-Z0-9_.]+(?:Exception|Error))(?::\s*(?P<msg>.*))?$")
NOISE = [re.compile(r"\d+"), re.compile(r"[0-9a-f]{8,}", re.I), re.compile(r"\.java:\d+")]


def fingerprint(text: str) -> str:
    s = text.lower()
    s = NOISE[2].sub(".java:N", s)
    s = NOISE[1].sub("<hex>", s)
    s = NOISE[0].sub("<n>", s)
    s = re.sub(r"\s+", " ", s).strip()[:200]
    return hashlib.sha1(s.encode()).hexdigest()[:10]


def main() -> None:
    trace_endpoint = {r.get("trace"): f"{r['method']} {endpoint_of(r['path'])}" for r in access()}
    path = SAMPLES / "error.log"
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []

    events = []
    current = None
    for line in lines:
        m = BLOCK.match(line)
        if m:
            current = {"ts": m.group("ts"), "level": m.group("level"), "trace": m.group("trace"),
                       "logger": m.group("logger"), "msg": m.group("msg"), "exception": None}
            events.append(current)
            continue
        e = EXCEPTION.match(line.strip())
        if e and current is not None and current["exception"] is None:
            current["exception"] = f"{e.group('type')}: {e.group('msg') or ''}".strip()

    groups: dict[str, list[dict]] = defaultdict(list)
    for ev in events:
        key = fingerprint(f"{ev['logger']} {ev['msg']} {ev['exception'] or ''}")
        groups[key].append(ev)

    doc = ["# Error catalogue", "",
           f"Generated by `kit/errors.py` from `samples/error.log`: **{len(events)} events**, "
           f"**{len(groups)} distinct signatures**.", "",
           "| Signature | Events | Level | Exception | Endpoint |", "|---|---|---|---|---|"]
    for fp, evs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        first = evs[0]
        ep = trace_endpoint.get(first["trace"], "(unknown)")
        doc.append(f"| `{fp}` | {len(evs)} | {first['level']} | `{(first['exception'] or '')[:70]}` | `{ep}` |")

    doc += ["", "## What each signature says about the code", ""]
    for fp, evs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        first = evs[0]
        ep = trace_endpoint.get(first["trace"], "(unknown)")
        doc.append(f"### `{fp}` — {len(evs)} event(s), endpoint `{ep}`")
        doc.append("")
        doc.append(f"- logger: `{first['logger']}`")
        doc.append(f"- message: {first['msg']}")
        if first["exception"]:
            doc.append(f"- exception: `{first['exception']}`")
        doc.append("- test to write: a request that produces exactly this signature, asserting the status and body")
        doc.append("")

    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/ERRORS.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    print(f"events={len(events)} signatures={len(groups)}")
    print("wrote docs/ERRORS.md")


if __name__ == "__main__":
    main()
