#!/usr/bin/env python3
"""Step 5 — the maps a future reader (human or AI) needs to answer: if I change X, what breaks?

Three outputs, all generated from the same logs, none written by hand:
  docs/SERVICES.md    service index: endpoints, tables, upstream callers, traffic share
  docs/SERVICE-MAP.md endpoint to endpoint, joined by trace id across services
  docs/IMPACT.md      reverse index: artifact -> dependents  (+ docs/impact.json for tooling)
"""
from __future__ import annotations

import json
from collections import defaultdict

from common import ROOT, SAMPLES, access, endpoint_of, read_jsonl, sql

TABLE = __import__("re").compile(r"\b(?:from|join|into|update)\s+([a-z_][a-z0-9_]*)", __import__("re").I)


def main() -> None:
    rpc = read_jsonl(SAMPLES / "rpc.log")
    acc = access()
    sqllog = sql()

    trace_endpoint = {r.get("trace"): f"{r['method']} {endpoint_of(r['path'])}" for r in acc}
    trace_tables: dict[str, set] = defaultdict(set)
    for row in sqllog:
        for t in TABLE.findall(row.get("sql", "")):
            if t.lower() not in ("select", "values", "set"):
                trace_tables[row.get("trace")].add(t.lower())

    services: dict[str, dict] = defaultdict(lambda: {"endpoints": set(), "tables": set(),
                                                    "callers": set(), "calls": set()})
    for r in rpc:
        caller, callee = r.get("caller"), r.get("callee")
        ep = f"{r['method']} {endpoint_of(r['path'])}"
        services[callee]["callers"].add(caller)
        services[caller]["calls"].add(callee)
        services[callee]["endpoints"].add(ep)
        if caller == "api-gateway":
            services[callee]["endpoints"].add(ep)
        services[callee]["tables"] |= trace_tables.get(r.get("trace"), set())

    # traffic share per service, from the gateway's own calls only
    total = sum(1 for r in rpc if r.get("caller") == "api-gateway") or 1
    share: dict[str, int] = defaultdict(int)
    for r in rpc:
        if r.get("caller") == "api-gateway":
            share[r["callee"]] += 1

    # ---------------- SERVICES.md
    doc = ["# Service index", "",
           "Generated by `kit/servicemap.py` from `samples/rpc.log` + `samples/sql.log` + `samples/access.log`.",
           "One row per service: what it exposes, what it stores, who calls it, how much traffic it carries.", ""]
    for name in sorted(services):
        s = services[name]
        doc += [f"## `{name}`", "",
                f"- traffic share: **{100.0 * share.get(name, 0) / total:.1f}%** of gateway calls",
                f"- callers: {', '.join(sorted(s['callers'])) or '(none — entry service)'}",
                f"- calls: {', '.join(sorted(s['calls'])) or '(none — leaf)'}",
                f"- endpoints: {', '.join(sorted(s['endpoints'])) or '(unknown)'}",
                f"- tables: {', '.join(sorted(s['tables'])) or '(none observed)'}", ""]
    (ROOT / "docs/SERVICES.md").write_text("\n".join(doc) + "\n", encoding="utf-8")

    # ---------------- SERVICE-MAP.md
    edges = sorted({(r["caller"], r["callee"], r["method"] + " " + endpoint_of(r["path"])) for r in rpc})
    doc = ["# Service map (endpoint to endpoint)", "",
           "Every edge was observed: same trace id in the access log, the RPC log and the SQL log.", "",
           "| Caller | Callee | Endpoint |", "|---|---|---|"]
    doc += [f"| `{a}` | `{b}` | `{c}` |" for a, b, c in edges]
    doc += ["", "```", "api-gateway"]
    for callee in sorted({b for a, b, _ in edges if a == "api-gateway"}):
        doc.append(f"  +-> {callee}")
        for b2 in sorted({b for a, b, _ in edges if a == callee}):
            doc.append(f"        +-> {b2}")
    doc += ["```", "",
            "## Why this matters for change", "",
            "An edge is a contract nobody wrote down. Touching `customer-svc` GET /api/customers/{id}",
            "affects `api-gateway`, `report-svc` and `order-svc` — three callers, three test suites to re-run."]
    (ROOT / "docs/SERVICE-MAP.md").write_text("\n".join(doc) + "\n", encoding="utf-8")

    # ---------------- IMPACT.md + impact.json
    impact: dict[str, dict] = defaultdict(lambda: {"type": "", "dependents": set(), "evidence": set()})
    for t, tables in trace_tables.items():
        for table in tables:
            impact[f"table:{table}"]["type"] = "database table"
            ep = trace_endpoint.get(t)
            if ep:
                impact[f"table:{table}"]["dependents"].add(f"endpoint {ep}")
            for r in rpc:
                if r.get("trace") == t:
                    impact[f"table:{table}"]["dependents"].add(f"service {r['callee']}")
                    impact[f"table:{table}"]["evidence"].add("samples/sql.log")
    for a, b, ep in edges:
        impact[f"endpoint:{ep}"]["type"] = "endpoint"
        impact[f"endpoint:{ep}"]["dependents"].add(f"caller {a}")
        impact[f"endpoint:{ep}"]["evidence"].add("samples/rpc.log")
    for name, s in services.items():
        impact[f"service:{name}"]["type"] = "service"
        impact[f"service:{name}"]["dependents"] |= {f"caller {c}" for c in s["callers"]}
        impact[f"service:{name}"]["dependents"] |= {f"table {t}" for t in s["tables"]}
        impact[f"service:{name}"]["evidence"].add("samples/rpc.log")

    doc = ["# Impact index — if you change this, what else must be checked", "",
           "Generated by `kit/servicemap.py`. Every row is derived from an observed trace, not from opinion.",
           "Machine-readable copy: `docs/impact.json` (same data, for a tool or an AI to query).", "",
           "| Artifact | Type | Dependents | Evidence |", "|---|---|---|---|"]
    for key in sorted(impact):
        v = impact[key]
        doc.append(f"| `{key}` | {v['type']} | {', '.join(sorted(v['dependents'])) or '—'} | "
                   f"{', '.join(sorted(v['evidence']))} |")
    doc += ["", "## How to use this with an AI assistant", "",
            "Ask: *\"which artifacts does `table:orders` touch?\"* — the answer is the row above, and the",
            "evidence column says which log proves it. Nothing here is generated from code comments, so it",
            "cannot drift the way a hand-written wiki drifts: regenerate and diff.", "",
            "A change that is not represented in this index is a change made blind."]
    (ROOT / "docs/IMPACT.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    (ROOT / "docs/impact.json").write_text(json.dumps(
        {k: {"type": v["type"], "dependents": sorted(v["dependents"]), "evidence": sorted(v["evidence"])}
         for k, v in sorted(impact.items())}, indent=2) + "\n", encoding="utf-8")

    print(f"services={len(services)} edges={len(edges)} impact_keys={len(impact)}")
    print("wrote docs/SERVICES.md docs/SERVICE-MAP.md docs/IMPACT.md docs/impact.json")


if __name__ == "__main__":
    main()
